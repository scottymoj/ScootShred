// pre-rendered glyph masks
const MASK = {};
for (const k in GL) MASK[k] = GL[k].map(r => [...r].map(c => c === "1"));

export function textWidth(s, sc = 1) { return s.length * 6 * sc - sc; }

export function drawText(ctx, s, x, y, col = "#fff", sc = 1, shadow = "#000") {
  s = String(s).toUpperCase();
  x = Math.round(x); y = Math.round(y);
  if (shadow) drawRaw(ctx, s, x + sc, y + sc, shadow, sc);
  drawRaw(ctx, s, x, y, col, sc);
}
function drawRaw(ctx, s, x, y, col, sc) {
  ctx.fillStyle = col;
  for (let n = 0; n < s.length; n++) {
    const m = MASK[s[n]] || MASK["?"];
    for (let r = 0; r < 7; r++) {
      const row = m[r];
      let c = 0;
      while (c < 5) {
        if (!row[c]) { c++; continue; }
        let e = c; while (e < 5 && row[e]) e++;
        ctx.fillRect(x + n * 6 * sc + c * sc, y + r * sc, (e - c) * sc, sc);
        c = e;
      }
    }
  }
}
export function drawTextC(ctx, s, cx, y, col, sc = 1, shadow = "#000") { drawText(ctx, s, cx - textWidth(String(s), sc) / 2, y, col, sc, shadow); }
export function drawTextR(ctx, s, rx, y, col, sc = 1, shadow = "#000") { drawText(ctx, s, rx - textWidth(String(s), sc), y, col, sc, shadow); }
